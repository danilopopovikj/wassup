	p := Propose(f, ProposeOptions{Name: "bookstore"})
	if got := f.candidate("backend").Env["DATABASE_URL"]; got != "postgresql://bookstore-db-rw:5432" {
		t.Errorf("DATABASE_URL = %q, want the host the variables resolve to", got)
	}
