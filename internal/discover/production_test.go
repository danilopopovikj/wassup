// TestRunsOn: where the pods run, or where the manifest sends them, or
// nothing.
func TestRunsOn(t *testing.T) {
	runs := func(p *Proposal, id string) string {
		c, _ := findComp(p.Topology.Components, id)
		return strings.Join(c.RunsOn, ",")
	}
	// the repository: a node selector names node-2; nothing else says a word
	p := Propose(scanProduction(t), ProposeOptions{Name: "bookstore"})
	if got := runs(p, "backend"); got != "node-2" {
		t.Errorf("backend selects node-2, runs_on = %q", got)
	}
	for _, id := range []string{"worker", "cache", "bookstore-electric", "ingress", "hatchet-engine"} {
		if got := runs(p, id); got != "" {
			t.Errorf("%s: nothing says where it runs, runs_on = %q", id, got)
		}
	}
	// the cluster: where the pods are
	_, lp := liveProposal(t)
	for id, want := range map[string]string{"backend": "node-1,node-3", "cache": "node-2", "app-electric": "node-2", "signoz": "node-3", "hatchet-engine": "", "ingress": ""} {
		if got := runs(lp, id); got != want {
			t.Errorf("%s runs_on = %q, want %q", id, got, want)
		}
	}
	// labels and taints
	nodes := []Candidate{
		{ID: "node-1", Type: "node", Name: "node-1", Labels: map[string]string{"role": "app"}},
		{ID: "node-2", Type: "node", Name: "node-2", Labels: map[string]string{"role": "db"}, Extra: map[string]string{"taints": "dedicated=db:NoSchedule"}},
		{ID: "node-3", Type: "node", Name: "node-3", Labels: map[string]string{"role": "db"}},
	}
	for _, c := range []struct{ selector, tolerations, want string }{
		{"role=db", "", "node-3"},
		{"role=db", "dedicated=db", "node-2,node-3"},
		{"role=db", "*", "node-2,node-3"},
		{"role=app|db", "dedicated", "node-1,node-2,node-3"},
		{"kubernetes.io/hostname=node-1", "", "node-1"},
		{"role=cache", "", ""},
		{"", "dedicated=db", ""}, // a toleration allows, it does not place
	} {
		got := strings.Join(runsOn(Candidate{Extra: map[string]string{"node_selector": c.selector, "tolerations": c.tolerations}}, nodes), ",")
		if got != c.want {
			t.Errorf("selector %q tolerations %q: runs on %q, want %q", c.selector, c.tolerations, got, c.want)
		}
	}
}

// TestProductIsOneComponent: the collector, the store, its coordination
// service and the agents of one observability stack are one component.
func TestProductIsOneComponent(t *testing.T) {
	check := func(name string, f *Findings, p *Proposal) {
		var obs []string
		for _, c := range p.Topology.Components {
			if c.Type == "observability" || strings.Contains(c.ID, "signoz") || strings.Contains(c.ID, "zookeeper") || strings.Contains(c.ID, "otel") {
				obs = append(obs, c.ID)
			}
		}
		if len(obs) != 1 || obs[0] != "signoz" {
			t.Errorf("%s: the stack should be the one component signoz, got %v", name, obs)
		}
		c := f.candidate("signoz")
		if c == nil {
			t.Fatalf("%s: no signoz", name)
		}
		listed := strings.Join(c.Objects, "; ") + " | " + mustJSON(t, c.Evidence)
		for _, w := range []string{"signoz-otel-collector", "signoz-zookeeper", "chi-signoz-clickhouse-cluster-0-0", "signoz-k8s-infra-otel-agent"} {
			if !strings.Contains(listed, w) {
				t.Errorf("%s: %s should be listed in the evidence of signoz: %s", name, w, listed)
			}
			if f.candidate(w) != nil {
				t.Errorf("%s: %s is still a candidate of its own", name, w)
			}
		}
		// the collector's Service now names the product
		if !hasEdge(p, "backend", "signoz", "tcp") {
			t.Errorf("%s: traces should flow to signoz: %v", name, p.Topology.Edges)
		}
	}
	f := scanProduction(t)
	check("repository", f, Propose(f, ProposeOptions{Name: "bookstore"}))
	lf, lp := liveProposal(t)
	check("cluster", lf, lp)
	// the repository first, the cluster after: still one
	AddCluster(f, liveInventory())
	check("repository and cluster", f, Propose(f, ProposeOptions{Name: "bookstore"}))
	if got := strings.Join(f.candidate("signoz").RunsOn, ","); got != "node-3" {
		t.Errorf("the product runs where its own pods run, not where every part does: %q", got)
	}

	// The application's own release is not a product: its parts stay.
	own := newAccumulator(&Findings{})
	for _, n := range []string{"api", "worker", "cache"} {
		img := "ghcr.io/bookstore/" + n + ":1"
		typ := "workload"
		if n == "cache" {
			img, typ = "redis:7", "cache"
		}
		own.add(Candidate{ID: n, Type: typ, Kind: "Deployment", Name: n, Namespace: "bookstore", Image: img,
			Labels: map[string]string{"app.kubernetes.io/instance": "bookstore", "app.kubernetes.io/part-of": "bookstore"}, Extra: map[string]string{"release": "bookstore"}})
	}
	own.finish()
	if len(own.f.Candidates) != 3 {
		t.Errorf("api, worker and cache of one release must stay three components: %+v", own.f.Candidates)
	}
}

// TestElectricBindingHasNoTable: with a table the probe asks Electric for a
// shape, and Electric answers a new shape with a snapshot query on the
// database. Discovery never proposes that.
func TestElectricBindingHasNoTable(t *testing.T) {
	_, fixture := scanFixture(t)
	_, live := liveProposal(t)
	proposals := map[string]*Proposal{"bookstore fixture": fixture, "production fixture": Propose(scanProduction(t), ProposeOptions{Name: "bookstore"}), "live cluster": live}
	for name, p := range proposals {
		seen := 0
		all := map[string][]model.ProbeSpec{}
		for id, specs := range p.Bindings.Components {
			all[id] = specs
		}
		for id, specs := range p.Bindings.Edges {
			all[id] = specs
		}
		for id, specs := range all {
			for _, s := range specs {
				if s.Kind() != "electric.sync" {
					continue
				}
				seen++
				if _, ok := s["table"]; ok {
					t.Errorf("%s: %s proposes electric.sync with table %v", name, id, s["table"])
				}
			}
		}
		if seen == 0 {
			t.Errorf("%s: no electric.sync binding to check", name)
		}
	}
	// the shapes the code reads are known (the fixtures read "issues" and
	// "items"), so leaving the table out is a choice
	if f, _ := scanFixture(t); f.candidate("electric").Extra["tables"] == "" {
		t.Error("the fixture should know a table, or this test checks nothing")
	}
}

func notesContain(notes []string, text string) bool {
	for _, n := range notes {
		if strings.Contains(n, text) {
			return true
		}
	}
	return false
}

func writeFile(t *testing.T, root, rel, content string) {
	t.Helper()
	p := filepath.Join(root, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

