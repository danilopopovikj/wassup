// liveProposal is the proposal of a run against the live cluster alone.
func liveProposal(t *testing.T) (*Findings, *Proposal) {
	t.Helper()
	f := &Findings{Root: t.TempDir()}
	AddCluster(f, liveInventory())
	return f, Propose(f, ProposeOptions{Name: "bookstore", Namespace: "default"})
}

func assertNoSecret(t *testing.T, what, text string) {
	t.Helper()
	for _, s := range secrets {
		if strings.Contains(text, s) {
			t.Errorf("%s holds the credential %q", what, s)
		}
	}
}

func mustJSON(t *testing.T, v any) string {
	t.Helper()
	b, err := json.Marshal(v)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

// TestNoCredentialIsWritten feeds a manifest, a ConfigMap and a live pod
// spec that hold passwords in plain, and checks everything discover writes
// or prints.
func TestNoCredentialIsWritten(t *testing.T) {
	f := scanProduction(t)
	assertNoSecret(t, "findings of the repository", mustJSON(t, f))
	AddCluster(f, liveInventory())
	assertNoSecret(t, "findings with the cluster", mustJSON(t, f))
	p := Propose(f, ProposeOptions{Name: "bookstore", Namespace: "default"})
	assertNoSecret(t, "proposal", mustJSON(t, p))

	dir := filepath.Join(t.TempDir(), model.DirName)
	if err := WriteProposal(dir, p, f); err != nil {
		t.Fatal(err)
	}
	// every file that was written, whatever it is called
	written := map[string]string{}
	err := filepath.WalkDir(dir, func(p string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		b, err := os.ReadFile(p)
		rel, _ := filepath.Rel(dir, p)
		written[filepath.ToSlash(rel)] = string(b)
		return err
	})
	if err != nil {
		t.Fatal(err)
	}
	for _, name := range []string{"topology.yaml", "bindings.yaml", "evidence.json"} {
		if written[ProposedDir+"/"+name] == "" {
			t.Errorf("%s was not written", name)
		}
	}
	for name, text := range written {
		assertNoSecret(t, name, text)
		// no URL anywhere carries a user
		if i := strings.Index(text, "@"); i >= 0 {
			t.Errorf("%s holds an @, which only the user of a URL would put there: %q", name, excerpt(text, i))
		}
	}
	// evidence.json embeds the findings; they are the ones checked above
	var ev map[string]json.RawMessage
	b, _ := os.ReadFile(filepath.Join(dir, ProposedDir, "evidence.json"))
	if err := json.Unmarshal(b, &ev); err != nil || ev["findings"] == nil || ev["evidence"] == nil {
		t.Errorf("evidence.json should hold the evidence and the findings: %v", err)
	}

	// The names stay, and so do the hosts: that is what the evidence is for.
	backend := f.candidate("backend")
	if backend == nil {
		t.Fatal("no backend")
	}
	for _, name := range []string{"POSTGRES_PASSWORD", "CLICKHOUSE_PASSWORD", "CLICKHOUSE_DSN", "DATABASE_URL", "HATCHET_CLIENT_TOKEN"} {
		if _, ok := backend.Env[name]; !ok {
			t.Errorf("the name %s should be kept", name)
		}
	}
	if backend.Env["POSTGRES_PASSWORD"] != "" || backend.Env["CLICKHOUSE_PASSWORD"] != "" {
		t.Errorf("a password keeps its name and nothing else: %v", backend.Env)
	}
	if got := backend.Env["HATCHET_CLIENT_TOKEN"]; got != "secret:hatchet/token" {
		t.Errorf("a secret reference names the secret: %q", got)
	}
	if got := backend.Env["CLICKHOUSE_DSN"]; got != "tcp://signoz-clickhouse.platform:9000" {
		t.Errorf("of a DSN only the host is kept: %q", got)
	}
	if cmd := backend.Extra["command"]; !strings.Contains(cmd, "uvicorn") || !strings.Contains(cmd, "--admin-password ***") {
		t.Errorf("the command should stay readable with its credentials masked: %q", cmd)
	}
}

func excerpt(s string, i int) string {
	from, to := max(0, i-40), min(len(s), i+40)
	return s[from:to]
}

// TestEnvFromConfigMap: the connection settings live in a ConfigMap the
// Deployments load with envFrom, in a ConfigMap Kustomize generates, and
// behind a configMapKeyRef.
func TestEnvFromConfigMap(t *testing.T) {
	f := scanProduction(t)
	p := Propose(f, ProposeOptions{Name: "bookstore"})
	for _, e := range [][3]string{
		{"backend", "bookstore-db", "sql"},                            // POSTGRES_SERVER, envFrom
		{"backend", "cache", "cache"},                                 // CACHE_HOST, envFrom
		{"backend", "hatchet-engine", "grpc"},                         // HATCHET_CLIENT_HOST_PORT, envFrom
		{"backend", "bookstore-electric", "http"},                     // ELECTRIC_URL, envFrom
		{"backend", "signoz", "tcp"},                                  // OTEL_EXPORTER_OTLP_ENDPOINT, envFrom
		{"worker", "cache", "cache"},                                  // CELERY_BROKER_URL, configMapGenerator literal
		{"worker", "bookstore-db", "sql"},                             // POSTGRES_SERVER, configMapKeyRef
		{"default-queue", "worker", "queue"},                          // celery -Q default
		{"bookstore-db-primary", "bookstore-electric", "replication"}, // DATABASE_URL of the sync service
	} {
		if !hasEdge(p, e[0], e[1], e[2]) {
			t.Errorf("missing edge %s -> %s (%s)", e[0], e[1], e[2])
		}
	}
	backend := f.candidate("backend")
	if got := backend.Env["POSTGRES_SERVER"]; got != "bookstore-db-rw" {
		t.Errorf("POSTGRES_SERVER from the ConfigMap = %q", got)
	}
	// A Secret is never read: the reference is all there is.
	if got := backend.Extra["env_from"]; !strings.Contains(got, "secret:app-secrets") || !strings.Contains(got, "configmap:app-config") {
		t.Errorf("env_from = %q", got)
	}
	// A ConfigMap that is not in the repository is said, not guessed.
	dir := t.TempDir()
	writeFile(t, dir, "deploy/api.yaml", `apiVersion: apps/v1
kind: Deployment
metadata:
  name: api
  namespace: bookstore
spec:
  template:
    spec:
      containers:
        - name: api
          image: ghcr.io/bookstore/api:1
          envFrom:
            - configMapRef:
                name: elsewhere
`)
	f2, err := Scan(Options{Root: dir})
	if err != nil {
		t.Fatal(err)
	}
	if !notesContain(f2.Notes, "elsewhere") {
		t.Errorf("a missing ConfigMap should be noted: %v", f2.Notes)
	}
}

